"""Render the facts card into a system-prompt block.

Two consumers:

* ``scripts/bake_system_prompts.py`` writes the block into every Ollama
  Modelfile's ``SYSTEM`` stanza, so a model served straight from Ollama carries
  the grounding even when the caller sends no system prompt of its own.
* ``facts.dataset`` uses :data:`SYSTEM_THOX` so the training-time system prompt
  matches the serving-time one. A model trained under one system prompt and
  served under a different one is being asked to generalise for no reason.

The block is delimited by markers so baking is idempotent and re-running after
a card update rewrites in place instead of appending a second copy.
"""

from __future__ import annotations

import textwrap

from .loader import ThoxFacts

#: The factory's house system prompt. Kept byte-identical to the string already
#: used in ``scripts/build_dataset.py`` so existing records stay consistent.
SYSTEM_THOX = (
    "You are a THOX assistant. Answer with terse, technical accuracy in the THOX house voice. "
    "No emojis. No marketing fluff. Local-first by default. Your AI. Your Data. Your Rules."
)

BEGIN_MARKER = "# >>> THOX FACTS (generated by facts/prompt.py — do not edit by hand) >>>"
END_MARKER = "# <<< THOX FACTS <<<"


def render_rule(facts: ThoxFacts) -> str:
    """The anti-fabrication rule, in the card's own words."""
    return (
        f"{facts.policy.rule} {facts.policy.precedence} "
        f"If asked something not covered here: {facts.policy.on_unknown}"
    )


def render_facts_block(facts: ThoxFacts, *, compact: bool = True) -> str:
    """Render the grounding block that goes into a model's system prompt.

    ``compact`` trims descriptions and keeps the block small enough to sit in
    every request's context on an edge model without crowding out the user turn.
    """
    site = facts.website.replace("https://", "").rstrip("/")
    lines: list[str] = ["THOX FACTS (authoritative; overrides anything you think you know):"]

    if facts.legal_name:
        lines.append(
            f"- Entity: {facts.legal_name}, a member-managed {facts.jurisdiction} "
            "limited liability company."
        )
    if facts.summary:
        lines.append(f"- What THOX is: {facts.summary}")
    founders = facts.founders()
    if founders:
        aliases = facts.founder_aliases()
        alias_note = ""
        for canonical, aka in aliases.items():
            # Only the operator-confirmed identity collision earns the tokens;
            # a middle-initial variant like "Craig A. Ross" does not.
            if aka and canonical.split()[0].lower() != aka[0].split()[0].lower():
                alias_note = f" ({aka[0]} and {canonical} are the same person.)"
                break
        # Titles became verified in card 1.1.0; render them when the card has them.
        titled = {
            str(person.get("name")): str(person.get("title"))
            for person in (facts.verified.get("people") or [])
            if isinstance(person, dict) and person.get("name") and person.get("title")
        }
        roster = ", ".join(
            f"{name} ({titled[name]})" if name in titled else name for name in founders
        )
        lines.append(f"- Co-founders, exactly two: {roster}.{alias_note}")
    if facts.hardware_names():
        lines.append(f"- Hardware: {', '.join(facts.hardware_names())}.")
    if facts.software_names():
        lines.append(f"- Software: {', '.join(facts.software_names())}.")
    if facts.published_models():
        lines.append(f"- Published models: {', '.join(facts.published_models())}.")
    if facts.software_license:
        # The card's value already reads "Apache-2.0 for core software", so a
        # "Core software licence:" label would stutter.
        lines.append(f"- Licence: {facts.software_license}.")
    if site:
        contact = f" Press: {facts.press_contact}." if facts.press_contact else ""
        lines.append(f"- Web: {site}.{contact}")

    if not compact:
        for item in facts.verified.get("software", []) or []:
            if isinstance(item, dict) and item.get("description"):
                lines.append(f"  - {item['name']}: {item['description']}")

    lines.append("")
    lines.append("NOT PUBLIC — never state, estimate, or infer these:")
    for entry in facts.unknown:
        topic = entry.topic.replace("_", " ")
        allowed = f" You may say: {entry.may_say}" if entry.may_say else ""
        lines.append(f"- {topic} ({entry.status}). {entry.must_not_say}{allowed}")

    if facts.pricing_rule():
        lines.append(f"- Pricing: {facts.pricing_rule()}")

    lines.append("")
    lines.append(f"RULE: {render_rule(facts)}")
    return "\n".join(lines)


def render_marked_block(facts: ThoxFacts, *, compact: bool = True) -> str:
    """The facts block wrapped in idempotency markers."""
    version = f"# card version {facts.version} (generated {facts.generated})"
    return "\n".join(
        [BEGIN_MARKER, version, render_facts_block(facts, compact=compact), END_MARKER]
    )


def bake(existing: str, facts: ThoxFacts, *, compact: bool = True) -> str:
    """Insert or replace the facts block inside an existing system prompt.

    Idempotent: baking twice yields the same string, and baking after a card
    update replaces the old block rather than stacking a second one.
    """
    block = render_marked_block(facts, compact=compact)
    start = existing.find(BEGIN_MARKER)
    if start == -1:
        base = existing.rstrip()
        return f"{base}\n\n{block}" if base else block
    end = existing.find(END_MARKER, start)
    if end == -1:
        # Truncated block from an interrupted write: replace from the marker on.
        return existing[:start].rstrip() + "\n\n" + block
    return existing[:start].rstrip() + "\n\n" + block + existing[end + len(END_MARKER) :]


def has_block(text: str) -> bool:
    return BEGIN_MARKER in text and END_MARKER in text


def render_system_prompt(base: str, facts: ThoxFacts, *, compact: bool = True) -> str:
    """A full default system prompt: the model's own persona plus grounding."""
    return bake(textwrap.dedent(base).strip(), facts, compact=compact)
